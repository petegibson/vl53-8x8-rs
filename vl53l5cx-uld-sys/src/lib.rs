// --- Status Codes ---
// Transcribed from `vl53l5cx_api.h`. They match the VL53L8CX codes (and so
// `vl53_8x8_types::FirmwareError::from`) except that code 3 is named
// `CRC_CSUM_FAILED` here rather than `LASER_SAFETY`, and there is no code 5
// (`FW_CHECKSUM_FAIL`). The L5 C sources never return code 3.
