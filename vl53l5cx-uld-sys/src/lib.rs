//! `vl53l5cx-uld-sys`: raw FFI bindings to the STMicroelectronics VL53L5CX ULD
//! (Ultra Lite Driver). The ULD C sources under `src/VL53L5CX_ULD_API/` are
//! compiled with `cc` and bound with `bindgen` at build time, so libclang is
//! required.
//!
//! This crate is **not published** and has no safe wrapper. It exists only as
//! a test oracle for the pure-Rust `vl53-8x8` driver, which derives its
//! VL53L5CX firmware and default configuration from the VL53L8CX ones by
//! applying small byte patches. The tests in `vl53-8x8` compare those patched
//! images against the arrays exported here.

// Include the bindings generated by build.rs
include!(concat!(env!("OUT_DIR"), "/bindings.rs"));

// The C struct `VL53L5CX_Configuration` does not derive Default.
impl Default for VL53L5CX_Configuration {
    fn default() -> Self {
        // Safe way to create a zero-initialized struct.
        unsafe { core::mem::zeroed() }
    }
}

// --- C Data Arrays ---
// Defined in `vl53l5cx_buffers.h` and compiled into the static library by
// build.rs. Array lengths were counted from the header and are checked by the
// `array_lengths_match_header_sizes` test below.
extern "C" {
    pub static VL53L5CX_FIRMWARE: [u8; 86016];
    pub static VL53L5CX_DEFAULT_CONFIGURATION: [u8; 972];
    pub static VL53L5CX_DEFAULT_XTALK: [u8; 776];
    pub static VL53L5CX_GET_NVM_CMD: [u8; 40];
}

// --- MANUAL CONSTANT DEFINITIONS ---
// Bindgen skips macros with explicit casts (e.g. ((uint16_t)0x5450U)), so the
// register map from `vl53l5cx_api.h` is transcribed here.

// --- UI Command Registers ---
pub const VL53L5CX_UI_CMD_STATUS: u16 = 0x2C00;
pub const VL53L5CX_UI_CMD_START: u16 = 0x2C04;
pub const VL53L5CX_UI_CMD_END: u16 = 0x2FFF;

// --- Data Sizes ---
pub const VL53L5CX_NVM_DATA_SIZE: u16 = 492;
pub const VL53L5CX_CONFIGURATION_SIZE: u16 = 972;
pub const VL53L5CX_OFFSET_BUFFER_SIZE: u16 = 488;
pub const VL53L5CX_XTALK_BUFFER_SIZE: u16 = 776;

// --- DCI Register Addresses ---
