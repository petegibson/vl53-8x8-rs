#[cfg(test)]
mod tests {
    use super::*;

    /// The `extern` array lengths above are not checked by the linker, so
    /// confirm them against the sizes the ULD header itself defines.
    #[test]
    fn array_lengths_match_header_sizes() {
        assert_eq!(
            unsafe { VL53L5CX_DEFAULT_CONFIGURATION.len() },
            VL53L5CX_CONFIGURATION_SIZE as usize
        );
        assert_eq!(
            unsafe { VL53L5CX_DEFAULT_XTALK.len() },
            VL53L5CX_XTALK_BUFFER_SIZE as usize
        );
        // The firmware image is the same size on both parts; the last byte of
        // the header's initializer is 0x00 and the array is non-trivial.
        let fw = unsafe { &VL53L5CX_FIRMWARE };
        assert!(fw.iter().any(|&b| b != 0));
    }

    /// The hand-written L5 status codes and mode values must agree with the
    /// shared L8-named ones in `vl53-8x8-types`, since `FirmwareError::from(u8)`
    /// and the `Resolution`/`PowerMode`/... enums are used for both parts.
    #[test]
    fn status_codes_and_modes_match_shared_types() {
        assert_eq!(VL53L5CX_STATUS_OK, VL53L8CX_STATUS_OK);
        assert_eq!(VL53L5CX_STATUS_TIMEOUT_ERROR, VL53L8CX_STATUS_TIMEOUT_ERROR);
        assert_eq!(VL53L5CX_STATUS_CORRUPTED_FRAME, VL53L8CX_STATUS_CORRUPTED_FRAME);
        assert_eq!(VL53L5CX_STATUS_XTALK_FAILED, VL53L8CX_STATUS_XTALK_FAILED);
        assert_eq!(VL53L5CX_MCU_ERROR, VL53L8CX_MCU_ERROR);
        assert_eq!(VL53L5CX_STATUS_INVALID_PARAM, VL53L8CX_STATUS_INVALID_PARAM);
        assert_eq!(VL53L5CX_STATUS_ERROR, VL53L8CX_STATUS_ERROR);
        assert_eq!(VL53L5CX_RESOLUTION_4X4, Resolution::Res4x4 as u8);
        assert_eq!(VL53L5CX_RESOLUTION_8X8, Resolution::Res8x8 as u8);
        assert_eq!(VL53L5CX_TARGET_ORDER_CLOSEST, TargetOrder::Closest as u8);
        assert_eq!(VL53L5CX_TARGET_ORDER_STRONGEST, TargetOrder::Strongest as u8);
        assert_eq!(VL53L5CX_RANGING_MODE_CONTINUOUS, RangingMode::Continuous as u8);
        assert_eq!(VL53L5CX_RANGING_MODE_AUTONOMOUS, RangingMode::Autonomous as u8);
        assert_eq!(VL53L5CX_POWER_MODE_SLEEP, PowerMode::Sleep as u8);
        assert_eq!(VL53L5CX_POWER_MODE_WAKEUP, PowerMode::Wakeup as u8);
    }

    /// The `targets-N` features must reach the C build and the bindgen pass:
    /// every per-target result array is `64 * VL53L5CX_NB_TARGET_PER_ZONE` long,
    /// while per-zone arrays stay at 64. Fields removed by `disable-*` features
    /// are skipped.
    #[test]
    fn per_target_result_arrays_scale_with_nb_target_per_zone() {
        let results: VL53L5CX_ResultsData = unsafe { core::mem::zeroed() };
        let zones = VL53L5CX_RESOLUTION_8X8 as usize;
        let per_target = zones * VL53L5CX_NB_TARGET_PER_ZONE;
        assert!(matches!(VL53L5CX_NB_TARGET_PER_ZONE, 1..=4));
        #[cfg(not(feature = "disable-distance"))]
        assert_eq!(results.distance_mm.len(), per_target);
        #[cfg(not(feature = "disable-target-status"))]
        assert_eq!(results.target_status.len(), per_target);
        #[cfg(not(feature = "disable-signal"))]
        assert_eq!(results.signal_per_spad.len(), per_target);
        #[cfg(not(feature = "disable-range-sigma"))]
        assert_eq!(results.range_sigma_mm.len(), per_target);
        #[cfg(not(feature = "disable-reflectance"))]
        assert_eq!(results.reflectance.len(), per_target);
        #[cfg(not(feature = "disable-nb-targets"))]
        assert_eq!(results.nb_target_detected.len(), zones);
        #[cfg(not(feature = "disable-ambient"))]
        assert_eq!(results.ambient_per_spad.len(), zones);
        let _ = (&results, zones, per_target);
    }
}
